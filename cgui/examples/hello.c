#include <cassette/cobj.h>
#include <cassette/cgui.h>
#include <stdio.h>
#include <unistd.h>

/************************************************************************************************************/
/************************************************************************************************************/
/************************************************************************************************************/

static void cl_close (cshell *, void *);
static void cl_open  (cshell *, void *);
static void cl_task  (cshell *, void *);

/************************************************************************************************************/
/* MAIN *****************************************************************************************************/
/************************************************************************************************************/

int
main(void)
{
	cshell *sh = cshell_create();

	cshell_on_open (sh,  cl_open, nullptr);
	cshell_on_close(sh, cl_close, nullptr);
	cshell_open(sh, CSHELL_ANY, "hello");
	cshell_rename(sh, "hello");
	cshell_wait(sh);

	cshell_invoke(sh, cl_task, &(int){1});
	cshell_invoke(sh, cl_task, &(int){2});
	cshell_invoke(sh, cl_task, &(int){3});
	cshell_join(sh);

	printf("done, errors: %s\n", cerr_name(cshell_error(sh)));
	cshell_destroy(sh);

	return 0;
}

/************************************************************************************************************/
/* STATIC ***************************************************************************************************/
/************************************************************************************************************/

static void
cl_close(cshell *sh, void *data)
{
	(void)data;
	(void)sh;

	printf("shell closed\n");
}

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

static void
cl_open(cshell *sh, void *data)
{
	(void)data;
	(void)sh;

	printf("shell opened\n");
}

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

static void
cl_task(cshell *sh, void *data)
{
	(void)sh;

	printf("executed task %i on UI thread\n", *(int *)data);
}
