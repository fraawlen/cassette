#define GUARD(CL, ...) if (!CL || cerr_critical(CL->err)) { return __VA_OPT__(__VA_ARGS__); }

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

struct call
{
	void (*fn)(ccell *, void *);
	void *data;
};

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

struct ccell
{
	/* state */

	enum cerr err;
	bool damaged;

	/* callbacks */

	struct call cl_event;
};

/************************************************************************************************************/
/************************************************************************************************************/
/************************************************************************************************************/

static void dummy (ccell *, void *);

/************************************************************************************************************/
/* PUBLIC ***************************************************************************************************/
/************************************************************************************************************/

void
ccell_clear_warnings(ccell *cl)
{
	GUARD(cl);

	cerr_clear_warnings(&cl->err);
}

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

ccell *
ccell_create(void)
{
	ccell *cl;

	if (!(cl = malloc(sizeof(ccell))))
	{
		return nullptr;
	}

	cl->err      = CERR_NONE;
	cl->cl_event = (struct call){.fn = dummy, .data = nullptr};
	cl->damaged  = false;

	return cl;
}

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

void
ccell_damage(ccell *cl)
{
	GUARD(cl);

	cl->damaged = true;

	// TODO signal shell
}

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

nullptr_t
ccell_destroy(ccell *cl)
{
	if (cl)
	{
		free(cl);
	}

	return nullptr;
}

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

enum cerr
ccell_error(const ccell *cl)
{
	return cl ? cl->err : CERR_INVALID;
}

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

void
ccell_on_event(ccell *cl, void (*fn)(ccell *, void *), void *data)
{
	GUARD(cl);

	cl->cl_event.fn   = fn ? fn : dummy;
	cl->cl_event.data = data;
}

/************************************************************************************************************/
/* PRIVATE **************************************************************************************************/
/************************************************************************************************************/

void
cell_send_event(ccell *cl, struct cevent ev)
{
	(void)cl;

	event_print(ev, "cell");
	switch (ev.type)
	{
		case CEVENT_TRANSFORM:
			cl->damaged = true;  // TODO
			break;

		case CEVENT_REDRAW:
			cl->damaged = false; // TODO
			break;

		default:
			break;
	}
}

/************************************************************************************************************/
/* STATIC ***************************************************************************************************/
/************************************************************************************************************/

/************************************************************************************************************/
/* STATIC - NOOP ********************************************************************************************/
/************************************************************************************************************/

static void
dummy(ccell *cl, void *data)
{
	(void)cl;
	(void)data;
}
