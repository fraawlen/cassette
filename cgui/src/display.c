#include <cassette/cgui.h>
#include <stdbool.h>
#include <stddef.h>
#include <stdio.h>
#include <stdlib.h>

#include "display.h"
#include "wayland.h"
#include "x11.h"

/************************************************************************************************************/
/************************************************************************************************************/
/************************************************************************************************************/

#define ROUTE(DP, FN, ...) \
	switch(DP->server) \
	{ \
		case CDISPLAY_WAYLAND: \
			wayland_##FN(&DP->wl __VA_OPT__(, __VA_ARGS__)); \
			break; \
		case CDISPLAY_X11: \
			x11_##FN(&DP->x __VA_OPT__(, __VA_ARGS__)); \
			break; \
		default: \
			break; \
	}

/************************************************************************************************************/
/* PUBLIC ***************************************************************************************************/
/************************************************************************************************************/

enum cdisplay_server
cdisplay_server(const cdisplay *dp)
{
	return dp ? dp->server : CDISPLAY_NONE;
}

/************************************************************************************************************/
/* PRIVATE **************************************************************************************************/
/************************************************************************************************************/

void
display_commit(cdisplay *dp, cshell *sh)
{
	ROUTE(dp, commit, sh);
}

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

void
display_dispatch(cdisplay *dp, cshell *sh)
{
	ROUTE(dp, dispatch, sh);
}

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

bool
display_init(cdisplay *dp, enum cdisplay_server server, uint32_t w, uint32_t h)
{
	if (server & CDISPLAY_WAYLAND && wayland_init(&dp->wl, &dp->fd, w, h))
	{
		dp->server = CDISPLAY_WAYLAND;
	}
	else if (server & CDISPLAY_X11 && x11_init(&dp->x, &dp->fd, w, h))
	{
		dp->server = CDISPLAY_X11;
	}
	else
	{
		return false;
	}
	
	return true;
}

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

void
display_kill(cdisplay *dp)
{
	ROUTE(dp, kill);

	dp->server = CDISPLAY_NONE;
	dp->fd     = -1;
}

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

void
display_redraw(cdisplay *dp)
{
	ROUTE(dp, redraw);
}
