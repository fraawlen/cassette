/************************************************************************************************************/
/************************************************************************************************************/
/************************************************************************************************************/

static void event (ccell *, void *, struct cevent);

/************************************************************************************************************/
/************************************************************************************************************/
/************************************************************************************************************/

static constexpr struct cbox_style default_style =
{
	.striped     = false,
	.pad         = 10,
	.border      = 10,
	.outline     = 1,
	.clr_border  = ccolor_green,
	.clr_outline = ccolor_blue,
	.clr_bg      = ccolor_red,
};

/************************************************************************************************************/
/* PUBLIC ***************************************************************************************************/
/************************************************************************************************************/

ccell *
cgap_create(void)
{
	cbox *frame = cbox_create("gap", 1);

	cbox_setup(frame, 0, default_style, "");

	return frame ? ccell_create(event, frame) : nullptr;
}

/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/

nullptr_t
cgap_destroy(ccell *cl)
{
	free(ccell_data(cl));

	return ccell_destroy(cl);
}

/************************************************************************************************************/
/* STATIC ***************************************************************************************************/
/************************************************************************************************************/

static void
event(ccell *cl, void *data, struct cevent ev)
{
	(void)cl;

	cbox *frame = data;

	switch (ev.type)
	{
		case CEVENT_DRAW:
			cbox_draw(frame, ev.drawable);
			break;

		case CEVENT_CONFIG:
			cbox_config(frame, ev.config);
			break;

		case CEVENT_SHAPE:
			cbox_shape(frame, ev.shape);
			break;
		
		default:
			break;
	}
}
