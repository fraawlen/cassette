#include <cassette/cobj.h>
#include <stdbool.h>
#include <stdint.h>

/************************************************************************************************************/
/* PUBLIC ***************************************************************************************************/
/************************************************************************************************************/

bool
carea_inside(struct carea area, int32_t x, int32_t y)
{
	return x >= area.x && (uint32_t)x - (uint32_t)area.x < area.w
	    && y >= area.y && (uint32_t)y - (uint32_t)area.y < area.h;
}
